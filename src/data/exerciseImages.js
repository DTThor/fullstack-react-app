export function getExerciseFrameUrls(exerciseName) {
  const key = exerciseName.toLowerCase().trim();
  const dbId = nameMap[key];
  if (!dbId) return null;
  return {
    frame0: `${BASE}/${dbId}/0.jpg`,
    frame1: `${BASE}/${dbId}/1.jpg`,
  };
}
